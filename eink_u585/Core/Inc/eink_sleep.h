/**
 * @file    eink_sleep.h
 * @brief   Сон МК по подсказке epd4g_wait_hint() для демо STM32U585.
 *
 * Пока панель рисует (0,3 .. 5 с), epd4g только ждёт: таймер или спад BUSY. Вместо опроса каждую
 * миллисекунду main-цикл спит в режиме Sleep (WFI), а будят его
 *   - спад BUSY (EXTI2, PB2) - панель закончила волну;
 *   - будильник TIM6 на срок, который вернул epd4g_wait_hint().
 *
 * Изменения в CubeMX не нужны: TIM6 и EXTI2 настраиваются из этого модуля на время сна (CubeMX
 * держит PB2 обычным входом; векторы TIM6_IRQHandler и EXTI2_IRQHandler определены здесь).
 *
 * На время сна SysTick останавливается, чтобы он не будил МК каждую миллисекунду. После пробуждения
 * HAL_GetTick() догоняется по TIM6 с точностью 0,1 мс без накопления ошибки, поэтому таймауты и
 * паузы библиотеки (epd4g_port_tick_ms() = HAL_GetTick()) остаются верными.
 */
#ifndef EINK_SLEEP_H
#define EINK_SLEEP_H

#include <stdint.h>

/* Один раз при старте, после SystemClock_Config() и MX_GPIO_Init(). */
void eink_sleep_init(void);

/*
 * Спать не дольше ms миллисекунд (ms = 0 - не спать; сверх ~6 с срок обрезается, ранний подъём
 * безвреден). При on_busy != 0 будит ещё и спад BUSY; если BUSY уже низкий, возвращается сразу.
 * Возвращает, сколько миллисекунд реально прошло (HAL_GetTick() за это время уже продвинут).
 * Вызывать из основного цикла, не из прерывания.
 */
uint32_t eink_sleep(uint32_t ms, int on_busy);

/* Статистика для отладки: число уходов в сон и суммарное время сна, мс. */
void eink_sleep_stats(uint32_t *count, uint32_t *total_ms);

#endif /* EINK_SLEEP_H */
