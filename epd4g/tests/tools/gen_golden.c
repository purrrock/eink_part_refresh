/*
 * Generates golden.inc: what the STOCK Waveshare library sends for Init_4GRAY, the 4-gray full
 * display of a fixed pseudo-random image, and Sleep. test_epd4g compares the epd4g library
 * against these values, so the library stays byte-compatible with the vendor sequence.
 *
 * Needs the Waveshare sources (https://github.com/waveshareteam/e-Paper):
 *   gcc -std=gnu11 -Istub -I<e-Paper>/STM32/STM32-F103ZET6/User/e-Paper tools/gen_golden.c \
 *       <e-Paper>/STM32/STM32-F103ZET6/User/e-Paper/EPD_2in7_V2.c -o gen_golden && ./gen_golden > golden.inc
 */
#include <stdio.h>
#include <string.h>
#include "EPD_2in7_V2.h"

static int dc, cs = 1;
static uint16_t stream[4096]; static int n;
static uint8_t p24[5808], p26[5808]; static int n24, n26, cur_cmd = -1;

void DEV_Digital_Write(UWORD pin, UBYTE v) { if (pin == EPD_DC_PIN) dc = v; else if (pin == EPD_CS_PIN) cs = v; }
UBYTE DEV_Digital_Read(UWORD pin) { (void)pin; return 0; }
void DEV_Delay_ms(UDOUBLE ms) { (void)ms; }
static void byte(UBYTE v)
{
    if (cs) return;
    if (!dc) { cur_cmd = v; if (v == 0x24) n24 = 0; if (v == 0x26) n26 = 0; }
    else if (cur_cmd == 0x24 && n24 < 5808) p24[n24++] = v;
    else if (cur_cmd == 0x26 && n26 < 5808) p26[n26++] = v;
    if (n < 4096) stream[n++] = (uint16_t)(v | (dc ? 0x100 : 0));
}
void DEV_SPI_WriteByte(UBYTE v) { byte(v); }
void DEV_SPI_Write_nByte(UBYTE *p, UDOUBLE len) { while (len--) byte(*p++); }

static uint32_t fnv(const uint8_t *p, int len) { uint32_t h = 2166136261u; while (len--) { h ^= *p++; h *= 16777619u; } return h; }

int main(void)
{
    static uint8_t img[11616];
    uint32_t s = 12345;
    for (int i = 0; i < 11616; i++) { s = s * 1103515245u + 12345u; img[i] = (uint8_t)(s >> 16); }

    n = 0; EPD_2IN7_V2_Init_4GRAY();
    printf("/* generated by tools/gen_golden.c from the stock Waveshare library - do not edit */\n");
    printf("/* Init_4GRAY: bit 8 set = data byte, clear = command */\nstatic const uint16_t golden_init[] = {");
    for (int i = 0; i < n; i++) printf("%s0x%03X,", i % 12 ? " " : "\n    ", stream[i]);
    printf("\n};\n#define GOLDEN_IMAGE_SEED 12345u\n");

    EPD_2IN7_V2_4GrayDisplay(img);
    printf("#define GOLDEN_PLANE24_LEN %d\n#define GOLDEN_PLANE24_FNV 0x%08Xu\n", n24, fnv(p24, n24));
    printf("#define GOLDEN_PLANE26_LEN %d\n#define GOLDEN_PLANE26_FNV 0x%08Xu\n", n26, fnv(p26, n26));

    n = 0; EPD_2IN7_V2_Sleep();
    printf("static const uint16_t golden_sleep[] = {");
    for (int i = 0; i < n; i++) printf(" 0x%03X,", stream[i]);
    printf(" };\n");
    return 0;
}
